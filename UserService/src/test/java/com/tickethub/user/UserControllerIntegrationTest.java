    @Test
    void shouldRegisterUserOnBothPathsWithAutoGeneratedIdAndReturnJwt() throws Exception {
        // 1. POST /api/users/register -> 201 Created
        RegisterRequest request1 = RegisterRequest.builder()
                .email("jai@example.com")
                .password("secret123")
                .phone("+919876543210")
                .fullName("Jai Kishan")
                .build();

        MvcResult result1 = mockMvc.perform(post("/api/users/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(request1)))
                .andExpect(status().isCreated())
                .andExpect(header().exists("X-Correlation-ID"))
                .andExpect(jsonPath("$.userId").isNumber())
                .andExpect(jsonPath("$.email").value("jai@example.com"))
                .andExpect(jsonPath("$.phone").value("+919876543210"))
                .andExpect(jsonPath("$.fullName").value("Jai Kishan"))
                .andExpect(jsonPath("$.role").value("CUSTOMER"))
                .andExpect(jsonPath("$.authProvider").value("LOCAL"))
                .andExpect(jsonPath("$.tokenType").value("Bearer"))
                .andExpect(jsonPath("$.token").isNotEmpty())
                .andReturn();

        AuthResponse response1 = objectMapper.readValue(
                result1.getResponse().getContentAsString(), AuthResponse.class);
        assertThat(response1.getUserId()).isNotNull().isPositive();

        Claims claims = jwtTokenService.parse(response1.getToken());
        assertThat(claims.getSubject()).isEqualTo("jai@example.com");
        assertThat(claims.get("preferred_username", String.class)).isEqualTo("jai@example.com");
        assertThat(((Number) claims.get("userId")).longValue()).isEqualTo(response1.getUserId());
        assertThat(claims.get("email", String.class)).isEqualTo("jai@example.com");
        assertThat(claims.get("phone", String.class)).isEqualTo("+919876543210");
        assertThat(claims.get("fullName", String.class)).isEqualTo("Jai Kishan");
        @SuppressWarnings("unchecked")
        List<Object> roles = (List<Object>) claims.get("roles");
        assertThat(roles).contains("ROLE_CUSTOMER");

        // 2. POST /auth/register -> 201 Created with distinct auto-generated userId
        RegisterRequest request2 = RegisterRequest.builder()
                .email("second@example.com")
                .password("secret123")
                .phone("+919876543211")
                .fullName("Second User")
                .build();

        MvcResult result2 = mockMvc.perform(post("/auth/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(request2)))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.userId").isNumber())
                .andExpect(jsonPath("$.email").value("second@example.com"))
                .andExpect(jsonPath("$.phone").value("+919876543211"))
                .andExpect(jsonPath("$.fullName").value("Second User"))
                .andExpect(jsonPath("$.token").isNotEmpty())
                .andReturn();

        AuthResponse response2 = objectMapper.readValue(
                result2.getResponse().getContentAsString(), AuthResponse.class);
        assertThat(response2.getUserId()).isGreaterThan(response1.getUserId());
    }

    @Test
    void shouldRejectDuplicateEmailAndInvalidRegistrationInput() throws Exception {
        RegisterRequest valid = RegisterRequest.builder()
                .email("duplicate@example.com")
                .password("secret123")
                .phone("+919876543210")
                .fullName("First User")
                .build();

        mockMvc.perform(post("/auth/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(valid)))
                .andExpect(status().isCreated());

        // Duplicate email -> 409 Conflict
        mockMvc.perform(post("/api/users/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(valid)))
                .andExpect(status().isConflict())
                .andExpect(jsonPath("$.status").value(409));

        // Invalid email -> 400 Bad Request
        RegisterRequest badEmail = RegisterRequest.builder()
                .email("not-an-email")
                .password("secret123")
                .phone("+919876543210")
                .build();
        mockMvc.perform(post("/api/users/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(badEmail)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.status").value(400));

        // Invalid phone -> 400 Bad Request
        RegisterRequest badPhone = RegisterRequest.builder()
                .email("valid@example.com")
                .password("secret123")
                .phone("abc-invalid")
                .build();
        mockMvc.perform(post("/api/users/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(badPhone)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.status").value(400));

        // Short password (< 6 chars) -> 400 Bad Request
        RegisterRequest shortPassword = RegisterRequest.builder()
                .email("valid2@example.com")
                .password("123")
                .phone("+919876543210")
                .build();
        mockMvc.perform(post("/api/users/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(shortPassword)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.status").value(400));
    }

    @Test
    void shouldLoginRegisteredUserAndRejectWrongPasswordOrUnknownEmail() throws Exception {
        RegisterRequest registerRequest = RegisterRequest.builder()
                .email("loginuser@example.com")
                .password("correctPass123")
                .phone("9876543210")
                .fullName("Login User")
                .build();

        mockMvc.perform(post("/api/users/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(registerRequest)))
                .andExpect(status().isCreated());

        // Login via /api/users/login using email -> 200 OK
        mockMvc.perform(post("/api/users/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"loginuser@example.com\",\"password\":\"correctPass123\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").isNumber())
                .andExpect(jsonPath("$.email").value("loginuser@example.com"))
                .andExpect(jsonPath("$.token").isNotEmpty());

        // Login via /auth/user-login using username alias -> 200 OK
        mockMvc.perform(post("/auth/user-login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"username\":\"loginuser@example.com\",\"password\":\"correctPass123\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.email").value("loginuser@example.com"))
                .andExpect(jsonPath("$.token").isNotEmpty());

        // Invalid password -> 401 Unauthorized
        mockMvc.perform(post("/api/users/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"loginuser@example.com\",\"password\":\"wrongPass\"}"))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.status").value(401));

        // Unknown email -> 401 Unauthorized
        mockMvc.perform(post("/auth/user-login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"unknown@example.com\",\"password\":\"correctPass123\"}"))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.status").value(401));
    }

    @Test
    void shouldSignUpAndSignInViaGoogleAndLinkExistingAccountAndReturnOAuthUrl() throws Exception {
        // 1. Google sign-up with simulated idToken payload on POST /api/users/auth/google
        String headerJson = Base64.getUrlEncoder().withoutPadding()
                .encodeToString("{\"alg\":\"RS256\",\"typ\":\"JWT\"}".getBytes(StandardCharsets.UTF_8));
        String payloadJson = Base64.getUrlEncoder().withoutPadding()
                .encodeToString(objectMapper.writeValueAsBytes(Map.of(
                        "sub", "google-sub-12345",
                        "email", "googleuser@gmail.com",
                        "name", "Google User"
                )));
        String simulatedIdToken = headerJson + "." + payloadJson + ".sig";

        GoogleAuthRequest googleRequest = GoogleAuthRequest.builder()
                .idToken(simulatedIdToken)
                .phone("+919123456789")
                .build();

        MvcResult signUpResult = mockMvc.perform(post("/api/users/auth/google")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(googleRequest)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").isNumber())
                .andExpect(jsonPath("$.email").value("googleuser@gmail.com"))
                .andExpect(jsonPath("$.fullName").value("Google User"))
                .andExpect(jsonPath("$.phone").value("+919123456789"))
                .andExpect(jsonPath("$.authProvider").value("GOOGLE"))
                .andExpect(jsonPath("$.role").value("CUSTOMER"))
                .andExpect(jsonPath("$.token").isNotEmpty())
                .andReturn();

        AuthResponse firstAuth = objectMapper.readValue(
                signUpResult.getResponse().getContentAsString(), AuthResponse.class);

        // 2. Subsequent Google sign-in via POST /auth/google returns same userId
        GoogleAuthRequest secondRequest = GoogleAuthRequest.builder()
                .email("googleuser@gmail.com")
                .googleSub("google-sub-12345")
                .fullName("Google User Updated")
                .build();

        mockMvc.perform(post("/auth/google")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(secondRequest)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").value(firstAuth.getUserId()))
                .andExpect(jsonPath("$.fullName").value("Google User Updated"));

        // 3. Link an existing LOCAL user when signing in via Google with the same email
        RegisterRequest localUser = RegisterRequest.builder()
                .email("localtogoogle@example.com")
                .password("secret123")
                .phone("+919000111222")
                .fullName("Local User")
                .build();
        MvcResult localReg = mockMvc.perform(post("/api/users/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(localUser)))
                .andExpect(status().isCreated())
                .andReturn();
        AuthResponse localAuth = objectMapper.readValue(
                localReg.getResponse().getContentAsString(), AuthResponse.class);

        GoogleAuthRequest linkRequest = GoogleAuthRequest.builder()
                .email("localtogoogle@example.com")
                .googleSub("google-sub-linked-999")
                .build();
        mockMvc.perform(post("/api/users/auth/google")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(linkRequest)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").value(localAuth.getUserId()))
                .andExpect(jsonPath("$.email").value("localtogoogle@example.com"));

        // 4. Google OAuth URL endpoints (both /api/users/auth/google/url and /auth/google/url)
        mockMvc.perform(get("/api/users/auth/google/url"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.authorizationUrl").exists())
                .andExpect(jsonPath("$.redirectUri").exists());

        mockMvc.perform(get("/auth/google/url"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.authorizationUrl").exists())
                .andExpect(jsonPath("$.redirectUri").exists());
    }

    @Test
    void shouldLookupAndUpdateUserProfileWithOwnershipAndAdminChecks() throws Exception {
        RegisterRequest registerRequest = RegisterRequest.builder()
                .email("profile@example.com")
                .password("secret123")
                .phone("+919998887776")
                .fullName("Original Name")
                .build();

        MvcResult regResult = mockMvc.perform(post("/api/users/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(registerRequest)))
                .andExpect(status().isCreated())
                .andReturn();

        AuthResponse auth = objectMapper.readValue(
                regResult.getResponse().getContentAsString(), AuthResponse.class);
        Long userId = auth.getUserId();

        // GET /api/users/{userId} -> 200 OK & 404 Not Found
        mockMvc.perform(get("/api/users/" + userId))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").value(userId))
                .andExpect(jsonPath("$.email").value("profile@example.com"))
                .andExpect(jsonPath("$.phone").value("+919998887776"));

        mockMvc.perform(get("/api/users/999999"))
                .andExpect(status().isNotFound())
                .andExpect(jsonPath("$.status").value(404));

        // GET /api/users/internal/{userId} -> 200 OK & 404 Not Found
        mockMvc.perform(get("/api/users/internal/" + userId))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").value(userId))
                .andExpect(jsonPath("$.email").value("profile@example.com"));

        mockMvc.perform(get("/api/users/internal/999999"))
                .andExpect(status().isNotFound())
                .andExpect(jsonPath("$.status").value(404));

        // GET /api/users/by-email -> 200 OK & 404 Not Found
        mockMvc.perform(get("/api/users/by-email").param("email", "profile@example.com"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").value(userId));

        mockMvc.perform(get("/api/users/by-email").param("email", "missing@example.com"))
                .andExpect(status().isNotFound())
                .andExpect(jsonPath("$.status").value(404));

        // GET /api/users/me via X-User-Id header -> 200 OK
        mockMvc.perform(get("/api/users/me").header("X-User-Id", String.valueOf(userId)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.email").value("profile@example.com"));

        // GET /api/users/me via X-Authenticated-Email header -> 200 OK
        mockMvc.perform(get("/api/users/me").header("X-Authenticated-Email", "profile@example.com"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").value(userId));

        // GET /api/users/me via Authorization Bearer header -> 200 OK
        mockMvc.perform(get("/api/users/me").header("Authorization", "Bearer " + auth.getToken()))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").value(userId));

        // GET /api/users/me without authentication -> 401 Unauthorized
        mockMvc.perform(get("/api/users/me"))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.status").value(401));

        // PUT /api/users/{userId} by owner -> 200 OK (updating fullName, phone, password)
        UpdateUserRequest updateRequest = UpdateUserRequest.builder()
                .fullName("Updated Name")
                .phone("+919111222333")
                .password("newSecret456")
                .build();

        mockMvc.perform(put("/api/users/" + userId)
                        .header("X-User-Id", String.valueOf(userId))
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(updateRequest)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.fullName").value("Updated Name"))
                .andExpect(jsonPath("$.phone").value("+919111222333"));

        // Verify updated password works for login
        mockMvc.perform(post("/api/users/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"profile@example.com\",\"password\":\"newSecret456\"}"))
                .andExpect(status().isOk());

        // PUT /api/users/{userId} by ADMIN -> 200 OK
        UpdateUserRequest adminUpdate = UpdateUserRequest.builder()
                .fullName("Admin Updated Name")
                .build();

        mockMvc.perform(put("/api/users/" + userId)
                        .header("X-User-Id", "1")
                        .header("X-Authenticated-Role", "ADMIN")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(adminUpdate)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.fullName").value("Admin Updated Name"));

        // PUT /api/users/{userId} by different non-admin CUSTOMER -> 403 Forbidden
        mockMvc.perform(put("/api/users/" + userId)
                        .header("X-User-Id", "99999")
                        .header("X-Authenticated-Role", "CUSTOMER")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(updateRequest)))
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.status").value(403));
    }
